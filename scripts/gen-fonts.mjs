// gen-fonts: writes the self-hosted font faces from the vendored woff2 in
// src/styles/fonts (Fontsource 5.3.0, latin subset, licences beside them).
//   src/styles/fonts-local.css   @font-face over ./fonts/*.woff2, for a
//                                bundler or a page served over http
//   <out>/fonts-inline.css       the same faces as data: urls, for a page
//                                opened from file:// or baked offline
// Usage: node scripts/gen-fonts.mjs [outDir]   (outDir defaults to dist/styles)
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const dir = join(root, "src", "styles", "fonts");
const out = resolve(root, process.argv[2] ?? join("dist", "styles"));

const LATIN = "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD";

// family, file stem, weight, style, licence
const FACES = [
  ["Permanent Marker", "permanent-marker-latin-400-normal", 400, "normal", "Apache-2.0"],
  ["Special Elite", "special-elite-latin-400-normal", 400, "normal", "Apache-2.0"],
  ["IBM Plex Mono", "ibm-plex-mono-latin-400-normal", 400, "normal", "OFL-1.1"],
  ["IBM Plex Mono", "ibm-plex-mono-latin-500-normal", 500, "normal", "OFL-1.1"],
  ["IBM Plex Mono", "ibm-plex-mono-latin-600-normal", 600, "normal", "OFL-1.1"],
  ["IBM Plex Mono", "ibm-plex-mono-latin-700-normal", 700, "normal", "OFL-1.1"],
  ["VT323", "vt323-latin-400-normal", 400, "normal", "OFL-1.1"],
  ["Libre Baskerville", "libre-baskerville-latin-400-italic", 400, "italic", "OFL-1.1"],
];

const head = (how) => `/* ==========================================================================
   hack.build fonts, self-hosted. Generated by scripts/gen-fonts.mjs; do not
   edit by hand.
   ${how}
   The five faces, latin subset, from Fontsource 5.3.0. Permanent Marker and
   Special Elite are Apache-2.0; IBM Plex Mono, VT323 and Libre Baskerville
   are OFL-1.1. The licence texts ship in fonts/LICENSE-*.txt; keep them
   beside the files when you copy the faces anywhere.
   ========================================================================== */
`;

const face = ([family, stem, weight, style], src) =>
  `@font-face{font-family:'${family}';font-style:${style};font-weight:${weight};font-display:swap;src:${src} format('woff2');unicode-range:${LATIN}}`;

const local = head("Relative urls to ./fonts/*.woff2: for a bundler or a page over http.") +
  FACES.map((f) => face(f, `url('./fonts/${f[1]}.woff2')`)).join("\n") + "\n";
writeFileSync(join(root, "src", "styles", "fonts-local.css"), local);

const inline = head("Data urls: for a page opened from file:// or an offline bake. About 240 KB.") +
  FACES.map((f) => face(f, `url(data:font/woff2;base64,${readFileSync(join(dir, `${f[1]}.woff2`)).toString("base64")})`)).join("\n") + "\n";
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "fonts-inline.css"), inline);
console.log(`gen-fonts: ${FACES.length} faces, fonts-local.css and ${relative(root, join(out, "fonts-inline.css"))}`);
